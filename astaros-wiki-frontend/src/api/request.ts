import axios, {
  type AxiosInstance,
  type InternalAxiosRequestConfig,
  type AxiosResponse,
} from 'axios' //导入 Axios 库
import { ElMessage } from 'element-plus' //导入 Element Plus 消息组件

// ========================================================
// TypeScript 类型定义
// ========================================================

// --------------------------------------------------------
// 统一响应结构
// --------------------------------------------------------
// 【学习要点】TypeScript interface 定义数据类型
//
// Result<T>: 泛型接口，T 表示 data 的类型
// 后端返回格式：{ code: 200, msg: "成功", data: {...} }
export interface Result<T = any> {
  //定义统一响应结构
  code: number // 响应码（200=成功，其他=失败）
  msg: string // 响应消息
  data: T // 响应数据（泛型）
}

export interface PageResult<T = any> {
  content: T[]
  total: number
  page: number
  size: number
  totalPages: number //总页数
}

// ========================================================
// 创建 Axios 实例
// ========================================================
// 【学习要点】创建独立的 Axios 实例，避免全局污染
//
// baseURL: '/api' - 所有请求自动添加 /api 前缀
// timeout: 10000 - 请求超时时间（10秒）
const service: AxiosInstance = axios.create({
  //创建 Axios 实例，继承 axios 配置项
  baseURL: '/api', // 基础 URL（Vite 代理到后端）
  timeout: 10000, // 请求超时时间（毫秒）
})

// ========================================================
// 请求拦截器
// ========================================================
// 【学习要点】拦截器在请求发送前执行
//
// 用途：
// 1. 添加请求头（如 Authorization）
// 2. 修改请求参数
// 3. 添加请求日志
service.interceptors.request.use(
  //是方法重写吗？是
  // --------------------------------------------------------
  // 成功拦截函数
  // --------------------------------------------------------
  // config: 请求配置对象
  (config: InternalAxiosRequestConfig) => {
    //请求拦截函数，这段语句是什么意思
    // --------------------------------------------------------
    // 从 localStorage 获取 Token
    // --------------------------------------------------------
    // localStorage: 浏览器本地存储
    // getItem('token'): 获取存储的 JWT Token
    const token = localStorage.getItem('token') //从 localStorage 获取 Token，这段语句是什么意思？从 localStorage 中获取存储的 JWT Token

    // --------------------------------------------------------
    // 如果 Token 存在，添加到请求头
    // --------------------------------------------------------
    // Authorization: JWT 认证的标准请求头
    // 格式：Bearer {token}
    if (token && config.headers) {
      //如果 Token 存在且请求头存在
      config.headers.Authorization = `Bearer ${token}` //将 Token 添加到请求头中，格式为 Bearer {token}
    }

    // --------------------------------------------------------
    // 返回修改后的配置
    // --------------------------------------------------------
    // 必须返回 config，否则请求不会发送
    return config //返回修改后的请求配置对象
  },

  // --------------------------------------------------------
  // 错误拦截函数
  // --------------------------------------------------------
  // error: 请求配置错误
  (error) => {
    //请求拦截函数，这段语句是什么意思
    // --------------------------------------------------------
    // 返回 Promise.reject，触发后续错误处理
    return Promise.reject(error) //返回 Promise.reject，触发后续错误处理
  },
)

// ========================================================
// 响应拦截器
// ========================================================
// 【学习要点】拦截器在响应返回后执行
//
// 用途：
// 1. 处理响应数据
// 2. 统一错误处理
// 3. 处理特定状态码（如 401）
service.interceptors.response.use(
  // --------------------------------------------------------
  // 成功拦截函数
  // --------------------------------------------------------
  // response: Axios 响应对象
  // 返回 response.data 而非完整的 AxiosResponse，简化调用
  (response: AxiosResponse<Result<any>>): any => {
    //响应拦截函数，这段语句是什么意思？返回响应数据，简化调用
    const res = response.data //从 Axios 响应对象中提取响应数据
    // --------------------------------------------------------
    // 检查响应状态码
    // --------------------------------------------------------
    // 200: 成功
    // 400: 客户端错误（如参数错误）
    // 401: 未认证（需要登录）
    // 403: 无权限（认证成功但无访问权限）
    // 404: 资源不存在
    // 500: 服务器错误
    if (res.code !== 200) {
      ElMessage.error(res.msg || '请求失败')
      return Promise.reject(new Error(res.msg || '请求失败'))
    }
    return res //返回响应数据，简化调用
  },

  // --------------------------------------------------------
  // 错误拦截函数
  // --------------------------------------------------------
  // error: HTTP 错误对象
  (error) => {
    // --------------------------------------------------------
    // 检查是否有响应
    // --------------------------------------------------------
    // error.response: HTTP 响应对象
    if (error.response) {
      // --------------------------------------------------------
      // 处理 401 未认证错误
      // --------------------------------------------------------
      // 401: Token 无效或过期
      if (error.response.status === 401) {
        // --------------------------------------------------------
        // 清除本地存储的认证信息
        // --------------------------------------------------------
        localStorage.removeItem('token')
        localStorage.removeItem('user')

        // --------------------------------------------------------
        // 跳转到登录页面
        // --------------------------------------------------------
        // window.location.href: 浏览器跳转
        window.location.href = '/login'
      }
      // --------------------------------------------------------
      // 处理 403 无权限错误
      // --------------------------------------------------------
      // 403: 用户无权限访问该资源
      else if (error.response.status === 403) {
        ElMessage.error('无权限访问')
      }
      // --------------------------------------------------------
      // 处理其他错误
      // --------------------------------------------------------
      else {
        ElMessage.error(error.response.data?.msg || '请求失败')
      }
    }
    // --------------------------------------------------------
    // 处理网络错误
    // --------------------------------------------------------
    // error.response 不存在表示网络问题
    else {
      ElMessage.error('网络错误')
    }

    // --------------------------------------------------------
    // 返回 Promise.reject
    // --------------------------------------------------------
    // 触发调用处的 catch 块
    return Promise.reject(error)
  },
)

// ========================================================
// 封装请求方法
// ========================================================
// 【学习要点】封装常用的请求方法，简化调用
//
// 使用方式：
// import { get, post } from '@/api/request'
// const res = await get('/users')
// const res = await post('/login', { username, password })
// ========================================================

// --------------------------------------------------------
// GET 请求方法
// --------------------------------------------------------
// url: 请求路径
// params: 查询参数（自动转为 ?key=value）
// Promise<Result<T>>: 返回 Promise，异步操作
export function get<T = any>(url: string, params?: any): Promise<Result<T>> {
  // service.get(): Axios GET 请求
  // { params }: 参数配置，Axios 自动转为查询参数
  return service.get(url, { params }) //返回 Promise，异步操作，处理响应数据
}

// --------------------------------------------------------
// POST 请求方法
// --------------------------------------------------------
// url: 请求路径
// data: 请求体数据（自动转为 JSON）
//post<T = any>(url: string, data?: any): Promise<Result<T>>: 返回 Promise，异步操作
//      - Result: 统一响应格式 { code, msg, data }，返回登录成功后的 AuthResponse 数据
//      - AuthResponse: data 的具体类型，包含 JWT 令牌、用户名、角色和用户 ID
export function post<T = any>(url: string, data?: any): Promise<Result<T>> {
  // service.post(): Axios POST 请求
  // data: 第二个参数是请求体
  return service.post(url, data) //返回 Promise，异步操作，处理响应数据
}

// --------------------------------------------------------
// PUT 请求方法
// --------------------------------------------------------
// url: 请求路径
// data: 请求体数据
export function put<T = any>(url: string, data?: any): Promise<Result<T>> {
  return service.put(url, data)
}

// --------------------------------------------------------
// DELETE 请求方法
// --------------------------------------------------------
// url: 请求路径
// 【学习要点】deleteRequest 避免与关键字冲突
export function deleteRequest<T = any>(url: string): Promise<Result<T>> {
  return service.delete(url)
}

// --------------------------------------------------------
// 导出 Axios 实例
// --------------------------------------------------------
// 用于其他模块导入
export default service
